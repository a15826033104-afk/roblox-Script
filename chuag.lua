local function b64(s)
	local C = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
	local m = {}
	for i = 1, 64 do m[C:sub(i, i)] = i - 1 end
	local t, n, buf, bits = {}, 0, 0, 0
	for i = 1, #s do
		local v = m[s:sub(i, i)]
		if v then
			buf = buf * 64 + v
			bits = bits + 6
			if bits >= 8 then
				bits = bits - 8
				local b = buf // 2 ^ bits
				buf = buf - b * 2 ^ bits
				n = n + 1
				t[n] = b
			end
		end
	end
	return t
end

local function lz(t)
	local out, n, i, len = {}, 0, 1, #t
	while i <= len do
		local f = t[i]
		i = i + 1
		for bit = 7, 0, -1 do
			if i > len then
				break
			end
			if f // 2 ^ bit % 2 == 1 then
				n = n + 1
				out[n] = t[i]
				i = i + 1
			else
				local b1, b2 = t[i], t[i + 1]
				i = i + 2
				local l = b1 // 16 + 3
				local src = n - ((b1 % 16) * 256 + b2)
				for k = 0, l - 1 do
					n = n + 1
					out[n] = out[src + k]
				end
			end
		end
	end
	local parts = {}
	for i2 = 1, n, 300 do
		local hi = i2 + 299
		if hi > n then
			hi = n
		end
		parts[#parts + 1] = string.char(table.unpack(out, i2, hi))
	end
	return table.concat(parts), n
end

