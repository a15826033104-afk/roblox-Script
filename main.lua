local function decode(s, k)
	local C = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
	local m = {}
	for i = 1, 64 do m[C:sub(i, i)] = i - 1 end
	local out, n, buf, bits, pos = {}, 0, 0, 0, 0
	local kl = #k
	for i = 1, #s do
		local v = m[s:sub(i, i)]
		if v then
			buf = buf * 64 + v
			bits = bits + 6
			if bits >= 8 then
				bits = bits - 8
				local byte = buf // (2 ^ bits)
				buf = buf - byte * (2 ^ bits)
				pos = pos % kl + 1
				n = n + 1
				out[n] = string.char(bit32.bxor(byte, k[pos]))
			end
		end
	end
	return table.concat(out)
end

